// about.js -- the "How it works" page. Plain explanation of the model and the search.
// Numbers that come from the cost model are read from the city config so the text cannot drift from the code.

import { h, clear } from './util.js';

export function renderAbout(root, city) {
  const c = city.config;
  const tbl = (head, rows) => h('table', { class: 'plain' },
    h('thead', {}, h('tr', {}, head.map((t) => h('th', {}, t)))),
    h('tbody', {}, rows.map((r) => h('tr', {}, r.map((cell) => h('td', {}, cell))))));

  clear(root).append(
    h('h1', {}, 'How it works'),
    h('p', { class: 'lede' }, 'Interchange plans trips across a fictional city. Pick two places and it finds the route with the lowest total cost, using either A* or Dijkstra. Both run on the same network and the same costs, so the only difference you see is how much each one searches.'),

    h('h2', {}, 'The city is synthetic'),
    h('p', {}, `The ${city.stops.length} stops, ${city.lines.length} lines and walking links were generated by a script with a fixed random seed (${city.seed}). The map is a flat ${city.size_km} by ${city.size_km} km canvas, not a real place. Fixing the seed means the same city comes out every time, so results can be repeated and checked.`),

    h('h2', {}, 'What “cost” means'),
    h('p', {}, 'Each route is scored in minutes. The planner picks the route with the lowest total:'),
    tbl(['Part', 'What it is'], [
      ['Ride', 'Time on a vehicle, from the timetable between stops.'],
      ['Wait', `Half the line’s headway each time you board (factor ${c.wait_factor}). A bus every 10 minutes costs 5 minutes of waiting.`],
      ['Walk', `Walking at ${c.walk_speed_kmh} km/h with a ${Math.round((c.walk_detour - 1) * 100)}% detour, to or from a stop within ${c.access_radius_km * 1000} m, or between linked stops.`],
      ['Transfer penalty', `${c.transfer_penalty_min} minutes by default, added every time you change vehicle. The first boarding is free. This is not real time; it is how much the planner dislikes changing.`],
    ]),

    h('h2', {}, 'How a route is searched'),
    h('p', {}, 'A stop on its own is not enough to know the cost of leaving it, because the cost depends on which line you arrived on. So the search works on states: “on line M1, just arrived at stop 7” or “standing at stop 7”. Edges between states are riding, getting off, walking, boarding, and walking to the first and from the last stop.'),
    h('p', {}, 'Both algorithms keep a list of states to try next and always take the one with the smallest score. Dijkstra scores a state by what it cost to reach it. A* adds an estimate of what is left:'),
    h('p', {}, h('code', {}, 'score = cost so far + straight-line distance to the destination / fastest vehicle speed')),
    h('p', {}, `The estimate uses ${c.v_max_kmh} km/h, the fastest any edge can go. Because no real journey can beat that, the estimate never overshoots, so A* still finds the cheapest route. The code checks this on every edge rather than assuming it. In the code, Dijkstra is the same function with the estimate switched off.`),

    h('h2', {}, 'What you can do on the planner page'),
    h('ol', { class: 'steps' },
      h('li', {}, 'Choose a start and destination from the lists, or click stops or empty ground on the map.'),
      h('li', {}, 'Switch between A* and Dijkstra. The route and cost stay the same; the states expanded and time change.'),
      h('li', {}, 'Move the transfer penalty. Each change sends a new request, and the Python search runs again.'),
      h('li', {}, 'Open “Watch the search” to see which states each algorithm expanded, in order.'),
      h('li', {}, 'Read the cost breakdown: ride, wait, walk and transfer penalty add up exactly to the total.')),

    h('h2', {}, 'Where the numbers come from'),
    tbl(['On screen', 'Source'], [
      ['Routes, costs, breakdown, states expanded, time', 'Computed per request by the Python search code (astar.py, journey.py). The browser only draws the reply.'],
      ['Map, stops and lines', 'The city files in data/, sent by the server as JSON.'],
      ['Experiments page', 'CSV files in results/, written by experiments.py and read by the server. Nothing is typed into the page.'],
    ]),

    h('h2', {}, 'Limits to keep in mind'),
    h('p', {}, 'Timetables are frequency-based: a line runs every N minutes and you wait half of that on average, instead of following a clock. The city is small, so absolute search times are tiny and depend on the machine. The experiment page compares ratios and state counts for that reason.'));
}
